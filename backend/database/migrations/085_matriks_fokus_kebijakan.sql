CREATE TEMP TABLE _matriks_ind ON COMMIT DROP AS
SELECT DISTINCT ON (btrim(regexp_replace(lower(i.name), '[^a-z0-9]+', ' ', 'g')))
       i.id, btrim(regexp_replace(lower(i.name), '[^a-z0-9]+', ' ', 'g')) AS key
FROM sababuka.indicators i
WHERE i.origin_type = 'rpjmd_master'
ORDER BY btrim(regexp_replace(lower(i.name), '[^a-z0-9]+', ' ', 'g')), i.created_at;

INSERT INTO sababuka.indicator_matrix_meta
    (indicator_id, sheet_code, rpjmd_level, rpjmd_page, official_source, support_opd_text, opd_basis, note)
SELECT mi.id, m.sheet_code, m.rpjmd_level, m.rpjmd_page, m.official_source, m.support_opd_text, m.opd_basis, m.note
FROM _matriks m
JOIN _matriks_ind mi ON mi.key = btrim(regexp_replace(lower(m.indicator_name), '[^a-z0-9]+', ' ', 'g'))
ON CONFLICT (indicator_id) DO UPDATE SET
    sheet_code = EXCLUDED.sheet_code, rpjmd_level = EXCLUDED.rpjmd_level, rpjmd_page = EXCLUDED.rpjmd_page,
    official_source = EXCLUDED.official_source, support_opd_text = EXCLUDED.support_opd_text,
    opd_basis = EXCLUDED.opd_basis, note = EXCLUDED.note;

-- OPD penanggung jawab utama dan pendukung ke tabel relasi OPD (tidak menimpa baris yang sudah ada).
INSERT INTO sababuka.indicator_responsible_opd (indicator_id, organization_id, is_primary, basis)
SELECT mi.id, o.id, d.is_primary, d.basis
FROM _matriks_opd d
JOIN _matriks_ind mi ON mi.key = btrim(regexp_replace(lower(d.indicator_name), '[^a-z0-9]+', ' ', 'g'))
JOIN sababuka.organizations o ON o.code = d.org_code
ON CONFLICT DO NOTHING;

